"""
Should the drone carry its own balloon beacon? Numbers, not opinions.

  python tools/compare_balloon_carry.py [--drone-kg 2.0] [--beacon-kg 0.3] [--jammer-radius-m 1000]

Writes BALLOON_CARRY.md from the labelled physics in
upin/simulation/balloon_physics.py and the simulator's own jammer model:
the balloon a beacon needs, its drag on the drone, the deflated option,
the release timeline inside a jammer, the balloon-lifted drone, and one
comparison table against breadcrumbs, launch-site balloons and a tethered
aerostat. Every assumption is listed in the report.

Patent-pending. AIMCRS / Abheet Prem Manghnani.
"""

import argparse
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from upin.simulation.balloon_physics import (CD_SPHERE, CYLINDER_KG_PER_LITRE,  # noqa: E402
                                             ENVELOPE_KG_PER_M2, RHO_AIR, G,
                                             aerostat_blowdown, balloon_for_payload,
                                             blowdown_sigma_m, gas_cylinder_mass_kg,
                                             helium_net_lift_kg_per_m3, hover_thrust_n,
                                             sphere_drag_n)
from upin.simulation.beacons import ASCENT_MS  # noqa: E402
from upin.simulation.environment import DENIAL_DROP_DB  # noqa: E402

GNSS_CLEAR_DB = 10.0
"""**Assumption.** A balloon's GNSS receiver works again once the jammer's
C/N0 drop is below this."""
UNKNOWN_WIND_SIGMA_MS = 5.0


def clearance_altitude_m(jammer_radius_m: float) -> float:
    """Where the simulator's jammer model (6 dB per doubling) falls to
    GNSS_CLEAR_DB, taking the slant distance as the altitude."""
    return jammer_radius_m * 10 ** ((DENIAL_DROP_DB - GNSS_CLEAR_DB) / 20.0)


def report(drone_kg: float, beacon_kg: float, jammer_radius_m: float,
           thrust_to_mass: float = 22.5, max_wind_ms: float = 8.0) -> str:
    b = balloon_for_payload(beacon_kg, ASCENT_MS)
    hover = hover_thrust_n(drone_kg)
    max_thrust = drone_kg * thrust_to_mass
    L = ["# Carrying a balloon beacon on the drone: the numbers", "",
         "Generated by `tools/compare_balloon_carry.py` from labelled physics "
         "(`upin/simulation/balloon_physics.py`). These decide between designs; "
         "none of it is a measurement.", "",
         "## Assumptions", "",
         f"- helium net lift {helium_net_lift_kg_per_m3():.2f} kg/m³ at sea level, 15 °C; "
         f"sphere drag coefficient {CD_SPHERE} (falls at high Reynolds number: drags "
         f"below could be 2–4× smaller); air density {RHO_AIR} kg/m³",
         f"- envelope {ENVELOPE_KG_PER_M2} kg/m²; a 200-bar cylinder {CYLINDER_KG_PER_LITRE} kg "
         f"per litre of water capacity",
         f"- drone {drone_kg} kg, thrust-to-mass {thrust_to_mass} m/s² (hover at "
         f"{hover / max_thrust:.0%} throttle); beacon payload {beacon_kg} kg; balloon ascent "
         f"{ASCENT_MS} m/s",
         f"- the simulator's jammer: {DENIAL_DROP_DB:.0f} dB inside its radius, 6 dB less per "
         f"doubling of distance; a balloon's GNSS works again below {GNSS_CLEAR_DB:.0f} dB",
         f"- unknown wind sigma {UNKNOWN_WIND_SIGMA_MS} m/s while the balloon climbs", "",
         "## 1. The balloon a beacon needs", "",
         f"To lift {beacon_kg} kg and still climb at {ASCENT_MS} m/s: diameter "
         f"**{b['diameter_m']:.2f} m**, volume {b['volume_m3']:.2f} m³, envelope "
         f"{b['envelope_kg']:.2f} kg, helium {b['helium_kg']:.3f} kg. (Radiosonde practice "
         f"is 1.2–1.5 m at launch; the model's drag coefficient is conservative.)", "",
         "## 2. Carrying it inflated", "",
         "| Speed | Drag of the balloon | As a fraction of hover thrust | Of maximum thrust |",
         "|---|---:|---:|---:|"]
    for v in (5.0, 10.0, 15.0):
        d = sphere_drag_n(b["diameter_m"], v)
        L.append(f"| {v:.0f} m/s | {d:.1f} N | {d / hover:.0%} | {d / max_thrust:.0%} |")
    hold = 0.0
    for v in range(0, 40):
        if sphere_drag_n(b["diameter_m"], v) + hover > max_thrust * 0.8:
            break
        hold = float(v)
    L += ["", f"Holding position in wind with the balloon attached, keeping 20% thrust in "
          f"reserve: about **{hold:.0f} m/s** of wind at most. The balloon also fouls the "
          f"propellers and must be kept clear of them.", "",
          "## 3. Carrying it deflated", ""]
    c = gas_cylinder_mass_kg(b["volume_m3"])
    L += [f"Gas {c['gas_kg']:.3f} kg in a {c['cylinder_litres']:.2f} L cylinder weighing about "
          f"{c['cylinder_kg']:.2f} kg, plus the envelope {b['envelope_kg']:.2f} kg, parachute and "
          f"beacon {beacon_kg} kg: roughly **{c['cylinder_kg'] + b['envelope_kg'] + beacon_kg + 0.1:.1f} kg** "
          f"carried in steel (a composite cylinder about half that), inflation in flight "
          f"taking minutes. A cubic metre of gas at 200 bar is a 5-litre cylinder: "
          f"scuba-sized, not pocket-sized.", "",
          "## 4. Released inside a jammer: when does it become useful?", ""]
    alt = clearance_altitude_m(jammer_radius_m)
    climb_s = alt / ASCENT_MS
    drift_sigma = UNKNOWN_WIND_SIGMA_MS * climb_s
    L += [f"Released at the jammer's radius ({jammer_radius_m:.0f} m), the balloon's own GNSS "
          f"works again at about **{alt / 1000:.1f} km** up, **{climb_s / 60:.0f} minutes** later. "
          f"Until then its position is a dead-reckoned guess: wind unknown gives a sigma of "
          f"about **{drift_sigma / 1000:.1f} km** at that moment. After it, the beacon knows itself "
          f"to a few metres, but the drone has been without it for those minutes.", "",
          "## 5. The balloon-lifted drone", ""]
    lift_d = balloon_for_payload(drone_kg, 0.5)["diameter_m"]
    L += [f"To carry a {drone_kg} kg drone the balloon is about **{lift_d:.1f} m** across. Drag at "
          f"5 / 10 m/s: {sphere_drag_n(lift_d, 5):.0f} / {sphere_drag_n(lift_d, 10):.0f} N against the "
          f"{hover:.0f} N of hover thrust it replaces. Holding position in a 5 m/s wind takes "
          f"{sphere_drag_n(lift_d, 5) / max_thrust:.0%} of the drone's maximum thrust. Good for "
          f"loitering in calm air; not for a mission with transit.", "",
          "## 6. A tethered aerostat over the base", ""]
    for wind in (3.0, 8.0):
        off, h, ang = aerostat_blowdown(300.0, 3.0, 60.0, wind)
        sig = blowdown_sigma_m(300.0, 3.0, 60.0, wind, 2.0)
        L.append(f"- 300 m tether, 3 m aerostat with 60 N net lift, wind {wind:.0f} m/s: leans "
                 f"{ang:.0f}°, offset {off:.0f} m downwind at {h:.0f} m up; a 2 m/s wind "
                 f"uncertainty moves it ±{sig:.0f} m. Survey the anchor; measure the tether angle "
                 f"or track it from two sites to tighten that.")
    L += ["", "## Comparison", "",
          "| Option | Beacon knows itself to | Useful after | Mass on the drone | Coverage | Cost in flight |",
          "|---|---|---|---|---|---|",
          "| Launch-site balloon (layer 151) | ~5 m (own GNSS above the jammer) | before the mission | none | tens of km from 20–30 km up, 1.5–2 h per balloon | none |",
          f"| Carried balloon, released when jammed | ~{drift_sigma / 1000:.1f} km for {climb_s / 60:.0f} min, then ~5 m | {climb_s / 60:.0f} min after release | "
          f"~{c['cylinder_kg'] + b['envelope_kg'] + beacon_kg + 0.1:.1f} kg deflated, or unflyable inflated | grows as it climbs | heavy; drag if inflated |",
          "| Breadcrumbs (layer 152) | 2–20 m (the fix at release + fall drift) | immediately | tens of grams each | 1–3 km from the trail, line of sight | a dispenser |",
          "| Tethered aerostat over the base | 10–50 m (blowdown) | persistent | none | a few km round the base | none |", "",
          "**Verdict from these numbers:** drop breadcrumbs on the way in; fly launch-site "
          "balloons for area coverage; keep an aerostat over the base; do not carry balloons "
          "on the mission drone.", ""]
    return "\n".join(L)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--drone-kg", type=float, default=2.0)
    ap.add_argument("--beacon-kg", type=float, default=0.3)
    ap.add_argument("--jammer-radius-m", type=float, default=1000.0)
    ap.add_argument("--out", default="BALLOON_CARRY.md")
    a = ap.parse_args(argv)
    text = report(a.drone_kg, a.beacon_kg, a.jammer_radius_m)
    Path(a.out).write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
