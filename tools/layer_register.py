#!/usr/bin/env python
"""
The layer register: every layer in the registry, measured, in one table,
with what it needs and a salvage verdict -- so the owner can decide what
to keep, what to rebuild and what to leave.

    python tools/layer_register.py            # regenerates docs/LAYER_REGISTER.md

Status is MEASURED the way the README measures it (tools/generate_layer_docs.py
probe): the layer is built with nothing attached and read three times.
  DECLINES     reports no fix and says why -- honours the no-fabrication contract
  PLACEHOLDER  returns the same made-up reading every time
  FABRICATES   returns a different made-up reading every time
The verdict is mechanical, from the status and the operating class:
  WORKS         declines honestly; in the box, or not yet wired
  REBUILD       fabricates, but the hardware is drone-feasible: a new honest
                layer under the contract (the old code is a sketch, not a base)
  REBUILD IF    fabricates; only if the specialist hardware or the
                infrastructure is bought or exists where the drone flies
  NOT FOR DRONE ships, submarines, ground vehicles
  NOT DEPLOYABLE laboratory physics
  NOT OPERATIONAL the radio system it listens to no longer transmits
  SUPPORT       no position of its own
"""
import os
import sys

REPO = os.path.join(os.path.dirname(__file__), "..")
sys.path.insert(0, REPO)
sys.path.insert(0, os.path.dirname(__file__))

from generate_layer_docs import probe  # noqa: E402

from upin.layers.mission_catalog import BY_ID  # noqa: E402
from upin.layers.registry import ALL_LAYER_CLASSES  # noqa: E402
from upin.layers.requirements_catalog import (OperatingClass, catalogue_requirement,  # noqa: E402
                                              operating_class)

GROUPS = {"A": "Satellite & celestial", "B": "Inertial & timing", "C": "Magnetic & quantum",
          "D": "RF & terrestrial", "E": "Optical & vision", "F": "Acoustic", "G": "Gravity",
          "H": "Chemical, seismic, flow", "I": "Cosmic & atmospheric", "J": "Human & crowd",
          "K": "Systems intelligence", "Q": "Quantum"}

PHONE_AND_TOWER = ("celltower_l9", "ecid_d21", "otdoa_d22", "fiveg_d23", "wifi_l8", "wifirtt_d24",
                   "bluetooth_d08", "rffingerprint_k12", "lora_d07", "aprs_d19")


def hardware_names(lid, cls):
    req = getattr(cls, "REQUIRES", None) or catalogue_requirement(lid)
    if req is None:
        return []
    return [h.name for h in req.hardware]


def verdict(status, klass, lid, hw):
    if status == "DECLINES":
        e = BY_ID.get(lid)
        if e is not None and e.in_box:
            return "WORKS (simulation); in the box"
        if e is not None:
            return "WORKS (simulation); not wired into the box: " + e.enable.split(":")[0]
        return "WORKS (simulation); not wired into the box"
    need = ", ".join(hw[:3]) or "its sensor"
    if klass == OperatingClass.DRONE_READY:
        return f"REBUILD: needs {need}; a new honest layer under the contract"
    if klass == OperatingClass.SPECIALIST:
        return f"REBUILD IF bought: {need}"
    if klass == OperatingClass.INFRASTRUCTURE:
        return f"REBUILD IF it exists where the drone flies: {need}"
    if klass == OperatingClass.PLATFORM_SPECIFIC:
        return "NOT FOR DRONE (ships, submarines, ground vehicles)"
    if klass == OperatingClass.LABORATORY:
        return "NOT DEPLOYABLE (laboratory physics)"
    if klass == OperatingClass.SUPPORT:
        return "SUPPORT: no position of its own; rebuild with the layer it serves"
    if klass == OperatingClass.NOT_OPERATIONAL:
        return "NOT OPERATIONAL (the system it listens to no longer transmits)"
    return f"REBUILD IF: {need}"


def rows():
    out = []
    for lid, cls in ALL_LAYER_CLASSES.items():
        f = probe(lid, cls)
        inst = cls()
        klass = operating_class(lid) or "unknown"
        hw = hardware_names(lid, cls)
        out.append({"number": inst.layer_number, "name": f.name, "id": lid,
                    "group": inst.group.value, "status": f.status, "class": klass,
                    "hardware": hw, "verdict": verdict(f.status, klass, lid, hw)})
    return out


def render(rs=None) -> str:
    rs = rs if rs is not None else rows()
    total = len(rs)
    works = sum(1 for r in rs if r["status"] == "DECLINES")
    in_box = sum(1 for r in rs if r["verdict"].endswith("in the box"))
    by_verdict = {}
    for r in rs:
        key = r["verdict"].split(":")[0].split(" (")[0]
        by_verdict[key] = by_verdict.get(key, 0) + 1
    L = ["# Layer register: every layer, measured, with what it needs and a verdict", "",
         "Generated by `python tools/layer_register.py`. Status is measured by building each layer with "
         "nothing attached and reading it three times (the README's method). The verdict is mechanical, "
         "from the status and the operating class; it is a starting point for a decision, not the decision.",
         "", f"**{total} layers.** {works} work honestly (decline without input), {in_box} of them run in "
         f"the box today. The rest invent readings and are never loaded by the box.", "",
         "| Verdict | Layers |", "|---|---:|"]
    for k in ("WORKS", "REBUILD", "REBUILD IF bought", "REBUILD IF it exists where the drone flies",
              "NOT FOR DRONE", "NOT DEPLOYABLE", "NOT OPERATIONAL", "SUPPORT"):
        n = sum(v for key, v in by_verdict.items() if key.startswith(k) and
                not (k == "REBUILD" and key.startswith("REBUILD IF")))
        if n:
            L.append(f"| {k} | {n} |")
    L += ["", "## Phones, towers and local radio", "",
          "The question most asked: yes, these layers exist, and every one of them invents its reading "
          "today. Each needs the radio it names and a reference (tower or access-point positions, which "
          "in India means the operator's own survey or the telecom's data, under the Indian-source rule).",
          "", "| # | Layer | id | Status | Needs | Verdict |", "|---:|---|---|---|---|---|"]
    for r in rs:
        if r["id"] in PHONE_AND_TOWER:
            L.append(f"| {r['number']} | {r['name']} | `{r['id']}` | {r['status'].lower()} | "
                     f"{'; '.join(r['hardware']) or '-'} | {r['verdict']} |")
    for g, gname in GROUPS.items():
        grp = [r for r in rs if r["group"] == g]
        if not grp:
            continue
        w = sum(1 for r in grp if r["status"] == "DECLINES")
        L += ["", f"## Group {g}: {gname} ({len(grp)} layers, {w} work)", "",
              "| # | Layer | id | Status | Class | Needs | Verdict |", "|---:|---|---|---|---|---|---|"]
        for r in sorted(grp, key=lambda r: r["number"]):
            L.append(f"| {r['number']} | {r['name']} | `{r['id']}` | {r['status'].lower()} | {r['class']} | "
                     f"{'; '.join(r['hardware']) or '-'} | {r['verdict']} |")
    L += ["", "## How to read a REBUILD", "",
          "A fabricating layer's code produces numbers from the simulator's world or from nothing. "
          "Rebuilding one means: the real sensor's driver, the layer's own physics written against the "
          "no-fabrication contract (`upin/core/no_fabrication.py`: decline and say why when the input is "
          "missing), a simulation that speaks the sensor's own protocol, tests of its declines and its "
          "stated limits, and a mission-catalogue entry. The honest layers built so far (146 to 154) are "
          "the pattern; each took one commit.", ""]
    return "\n".join(L)


def main() -> int:
    text = render()
    path = os.path.join(REPO, "docs", "LAYER_REGISTER.md")
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"written {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
