"""
The mission index: every honest way UPIN gets a position, and which to
load for a mission.

  python tools/mission_index.py                       # regenerate docs/MISSION_INDEX.md
  python tools/mission_index.py --have flight_controller,gnss_receiver,camera,rangefinder --situation jammed
  python tools/mission_index.py --list                # the hardware tags and situations

The query mode prints what to load, why, each README, and a box.toml
fragment. It recommends only components that honour the no-fabrication
contract and are wired into the box; the layers that still invent readings
are listed in the index under "not usable on real hardware" and never
recommended.

Patent-pending. AIMCRS / Abheet Prem Manghnani.
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from upin.layers.mission_catalog import (BY_ID, ENTRIES, HARDWARE_TAGS, LADDERS,  # noqa: E402
                                         PROFILES, SITUATIONS, recommend)

OUT = Path("docs/MISSION_INDEX.md")


def _not_usable():
    from upin.layers.registry import ALL_LAYER_CLASSES
    from upin.layers.requirements_catalog import operating_class
    rows = []
    for k, cls in sorted(ALL_LAYER_CLASSES.items()):
        if k in BY_ID:
            continue
        honest = bool(getattr(cls, "NO_FABRICATION", False))
        rows.append((k, cls().name, operating_class(k),
                     "declines honestly; laboratory hardware" if honest else "invents readings"))
    return rows


def render() -> str:
    L = ["# Mission index: every honest way to get a position, and what to load", "",
         "Generated by `tools/mission_index.py` from `upin/layers/mission_catalog.py`. "
         "Regenerate after any change there. Every accuracy figure is a **simulation** "
         "figure until the bench says otherwise.", "",
         "Ask it directly:", "", "```bash",
         "python tools/mission_index.py --have flight_controller,gnss_receiver,camera,rangefinder --situation jammed",
         "```", "",
         "## Situations", "", "| Key | Meaning |", "|---|---|"]
    L += [f"| `{k}` | {v} |" for k, v in SITUATIONS.items()]
    L += ["", "## Hardware tags", "", "| Tag | Meaning |", "|---|---|"]
    L += [f"| `{k}` | {v} |" for k, v in HARDWARE_TAGS.items()]
    L += ["", "## Mission profiles", "",
          "What the index recommends for a few typical missions (yes = works; limited = works "
          "with the stated caveat).", ""]
    for name, sit, have in PROFILES:
        L += [f"### {name}", "", f"Situation `{sit}`; fitted: {', '.join(f'`{h}`' for h in sorted(have))}", ""]
        for e, verdict, why in recommend(sorted(have), sit):
            L.append(f"- **{e.name}** ({verdict}{': ' + why if why else ''}) — [{e.readme}](../{e.readme})")
        L.append("")
    L += ["## Fallback ladders", "",
          "When a rung is missing or declines, the next one carries on, at the cost shown.", ""]
    for what, rungs in LADDERS.items():
        L += [f"### {what.title()}", ""]
        L += [f"{i + 1}. **{BY_ID[rid].name}** — {cost}" for i, (rid, cost) in enumerate(rungs)]
        L.append("")
    L += ["## Every honest component", "",
          "| Component | Gives | Needs | Works when | Measured (simulation) | Enable | README | Status |",
          "|---|---|---|---|---|---|---|---|"]
    for e in ENTRIES:
        works = "; ".join(f"{SITUATIONS[s]}: {v}" + (f" ({w})" if w else "")
                          for s, (v, w) in e.works.items() if v != "yes")
        enable = e.enable.replace("\n", "<br>").replace("|", "\\|")
        L.append(f"| **{e.name}** `{e.layer_id}` | {', '.join(sorted(e.gives))} | "
                 f"{', '.join(f'`{n}`' for n in sorted(e.needs))} | {works or 'everywhere'} | "
                 f"{e.measured} | `{enable}` | [{e.readme}](../{e.readme}) | {e.status} |")
    L += ["", "## Not usable on real hardware yet", "",
          "Listed from the registry so nobody loads one by mistake. The box never loads them.", "",
          "| Layer | Name | Operating class | Why not |", "|---|---|---|---|"]
    L += [f"| `{k}` | {n} | {c} | {why} |" for k, n, c, why in _not_usable()]
    L.append("")
    return "\n".join(L)


def query(have, situation) -> str:
    recs = recommend(have, situation)
    L = [f"Situation: {SITUATIONS[situation]}; fitted: {', '.join(sorted(have))}", ""]
    if not recs:
        return "\n".join(L + ["Nothing usable: no honest component matches this hardware and situation."])
    L.append("Load, in this order:")
    toml = []
    for e, verdict, why in recs:
        L.append(f"  - {e.name} [{e.layer_id}] ({verdict}{': ' + why if why else ''})")
        L.append(f"      measured: {e.measured}")
        L.append(f"      README:   {e.readme}")
        if e.falls_back_to:
            L.append(f"      falls back to: {e.falls_back_to}")
        if "=" in e.enable and not e.enable.startswith("automatic") and not e.enable.startswith("always"):
            toml.append(f"# {e.name}\n{e.enable}")
    if toml:
        L += ["", "box.toml fragment:", ""] + toml
    return "\n".join(L)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--have", help="comma-separated hardware tags")
    ap.add_argument("--situation", choices=sorted(SITUATIONS))
    ap.add_argument("--list", action="store_true")
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args(argv)
    if a.list:
        print("hardware tags:\n  " + "\n  ".join(f"{k}: {v}" for k, v in HARDWARE_TAGS.items()))
        print("situations:\n  " + "\n  ".join(f"{k}: {v}" for k, v in SITUATIONS.items()))
        return
    if a.have or a.situation:
        if not (a.have and a.situation):
            ap.error("--have and --situation go together")
        print(query([h.strip() for h in a.have.split(",") if h.strip()], a.situation))
        return
    Path(a.out).write_text(render(), encoding="utf-8")
    print(f"wrote {a.out}: {len(ENTRIES)} honest components, {len(_not_usable())} not usable yet")


if __name__ == "__main__":
    main()
